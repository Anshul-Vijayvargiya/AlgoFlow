/**
 * Records the traces of the Playground's example programs (src/execution/traceSamples.ts) by running the real Python
 * tracer on them with the local Python, and writes them to src/execution/recordedTraces.generated.ts, marked
 * provenance 'fixture'. Test mode (the fake provider and the mock API) shows these, labelled as recorded samples.
 *
 *   npx tsx server/scripts/recordTraceFixtures.ts
 *
 * Only these fixed example programs are run, on the developer's machine; the server never runs any program.
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { randomBytes } from 'node:crypto';
import { buildPythonTraceProgram, extractTrace } from '../services/execution/tracing/pythonTracer';
import { validateTrace, type ExecutionTrace } from '../../src/execution/trace';
import { TRACE_SAMPLES } from '../../src/execution/traceSamples';

const PYTHON = process.env.PYTHON ?? 'python';
const OUT = join(import.meta.dirname, '../../src/execution/recordedTraces.generated.ts');

/** runs the tracer on one program with the local Python and returns its validated trace */
export function recordTrace(source: string, stdin: string): ExecutionTrace {
  const dir = mkdtempSync(join(tmpdir(), 'algoflow-trace-'));
  try {
    const nonce = randomBytes(16).toString('hex');
    const file = join(dir, 'tracer.py');
    writeFileSync(file, buildPythonTraceProgram(source, nonce));
    const stdout = execFileSync(PYTHON, ['-I', file], { input: stdin, encoding: 'utf8', timeout: 30_000 });
    const found = extractTrace(stdout, nonce);
    if (found.kind !== 'found') throw new Error(`no trace (${found.kind})`);
    const checked = validateTrace(JSON.parse(found.json), { source, stdin });
    if (!checked.ok) throw new Error(`invalid trace: ${checked.reason}`);
    return checked.trace;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

// run as a script (not when a test imports recordTrace)
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const recorded: Record<string, ExecutionTrace> = {};
  for (const sample of TRACE_SAMPLES) {
    recorded[sample.id] = { ...recordTrace(sample.source, sample.stdin), provenance: 'fixture' };
    console.log(`${sample.id}: ${recorded[sample.id].status}, ${recorded[sample.id].steps.length} steps`);
  }
  writeFileSync(
    OUT,
    `// GENERATED by server/scripts/recordTraceFixtures.ts — do not edit by hand.\n` +
      `// Traces of src/execution/traceSamples.ts recorded with the real Python tracer (provenance 'fixture').\n` +
      `import type { ExecutionTrace } from './trace';\n\n` +
      `export const RECORDED_TRACES: Record<string, ExecutionTrace> = ${JSON.stringify(recorded)};\n`
  );
  console.log(`wrote ${OUT}`);
}
