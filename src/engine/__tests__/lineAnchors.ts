  const add = (inner: Record<string, RegExp>, sites: string[]) => {
    for (const site of sites) for (const [ref, c] of Object.entries(inner)) anchors[`${ref}@${site}`] = new RegExp(`${c.source}|${LIBRARY[site].source}`);
  };
  add(C_INSERT, ['stone', 'diff']);
  add(C_POP, ['y', 'x']);
